_LAUGH_RE = re.compile(r'\b(?:wk|kw|ha|he|hi){2,}[a-z]*\b', re.IGNORECASE)
_REPEAT_CHAR_RE = re.compile(r'(.)\1{2,}')
_PUNCT_SPACE_RE = re.compile(r'([?!.,/()])')
_MULTI_SPACE_RE = re.compile(r'\s+')

def normalize_tiktok_text(text: str) -> str:
    """Menormalisasi komentar live TikTok (huruf kecil, reduplikasi huruf, tawa, & kamus slang)."""
    if not text:
        return ""
    s = str(text).lower().strip()
    s = _PUNCT_SPACE_RE.sub(r' \1 ', s)
    s = _REPEAT_CHAR_RE.sub(r'\1', s)
    s = _LAUGH_RE.sub(' ketawa ', s)
    tokens = s.split()
    mapped = [SLANG_MAP.get(tok, tok) for tok in tokens]
    return _MULTI_SPACE_RE.sub(' ', ' '.join(mapped)).strip()
